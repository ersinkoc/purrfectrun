export const messages: Record<Language, Messages> = { tr, en };
export function parseLanguage(value: string | null): Language {
  return value === 'en' ? 'en' : 'tr';
}
export function loadLanguage(): Language {
  try {
    return parseLanguage(localStorage.getItem(LANGUAGE_KEY));
  } catch {
    return 'tr';
  }
}
export function saveLanguage(language: Language) {
  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch {
    /* The selection remains available for this session. */
  }
}
